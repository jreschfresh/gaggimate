#!/usr/bin/env python3
"""Draws the Jungle icons (drop, espresso cup) as anti-aliased alpha masks and writes mod/jungle/jungle_icons.c.
Usage: python3 mod/make_icons.py [preview.png]"""
import sys, os
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import gaussian_filter

SS = 16  # supersampling


def bez(p0, p1, p2, p3, n=40):
    t = np.linspace(0, 1, n)[:, None]
    p0, p1, p2, p3 = map(np.array, (p0, p1, p2, p3))
    return ((1 - t) ** 3 * p0 + 3 * (1 - t) ** 2 * t * p1 + 3 * (1 - t) * t ** 2 * p2 + t ** 3 * p3).tolist()


def finish(img, w, h, soften):
    a = np.asarray(img, dtype=np.float32) / 255.0
    if soften > 0:  # rounds sharp corners: blur, then cut at 50 %
        a = (gaussian_filter(a, soften * SS) > 0.5).astype(np.float32)
    a = a.reshape(h, SS, w, SS).mean(axis=(1, 3))
    return (a * 255 + 0.5).astype(np.uint8)


def drop():
    w, h = 26, 34
    img = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(img)
    cx, cy, r = 13.0, 21.5, 9.5
    tip = (cx, 2.5)
    right = bez(tip, (cx + 0.5, 9.5), (cx + r, 13.5), (cx + r, cy))
    left = [(2 * cx - x, y) for x, y in right][::-1]
    d.polygon([(x * SS, y * SS) for x, y in right + left], fill=255)
    d.ellipse([(cx - r) * SS, (cy - r) * SS, (cx + r) * SS, (cy + r) * SS], fill=255)
    return finish(img, w, h, 0.9)


def cup():
    w, h = 28, 22
    img = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(img)
    cx = 11.5
    # bowl: wide rim, sides that curve in to a narrow base (the classic thick-walled Italian shape)
    right = bez((cx + 9.5, 2.0), (cx + 9.5, 9.5), (cx + 6.5, 14.0), (cx + 3.5, 14.5))
    left = [(2 * cx - x, y) for x, y in right][::-1]
    d.polygon([(x * SS, y * SS) for x, y in right + left], fill=255)
    # foot
    d.rounded_rectangle([(cx - 4) * SS, 13.5 * SS, (cx + 4) * SS, 16.2 * SS], radius=0.8 * SS, fill=255)
    # handle: a small ring high on the right side
    hx, hy, ro, ri = cx + 10.2, 6.6, 4.2, 2.3
    d.ellipse([(hx - ro) * SS, (hy - ro) * SS, (hx + ro) * SS, (hy + ro) * SS], fill=255)
    d.ellipse([(hx - ri) * SS, (hy - ri) * SS, (hx + ri) * SS, (hy + ri) * SS], fill=0)
    d.polygon([(x * SS, y * SS) for x, y in right + left], fill=255)  # bowl covers the inner half of the ring
    # saucer
    d.rounded_rectangle([(cx - 10.5) * SS + SS, 18.6 * SS, (cx + 10.5) * SS + SS, 20.6 * SS], radius=1.0 * SS, fill=255)
    return finish(img, w, h, 0.35)


def c_array(name, a):
    h, w = a.shape
    rows = ["    " + ", ".join("0x%02x" % v for v in row) + "," for row in a]
    return (
        "static const uint8_t %s_map[] = {\n%s\n};\n\n"
        "const lv_img_dsc_t %s = {\n"
        "    .header.cf = LV_IMG_CF_ALPHA_8BIT,\n    .header.always_zero = 0,\n    .header.reserved = 0,\n"
        "    .header.w = %d,\n    .header.h = %d,\n    .data_size = %d,\n    .data = %s_map,\n};\n\n"
        % (name, "\n".join(rows), name, w, h, w * h, name)
    )


ICONS = {"jungle_icon_drop": drop(), "jungle_icon_cup": cup()}

here = os.path.dirname(os.path.abspath(__file__))
with open(os.path.join(here, "jungle", "jungle_icons.c"), "w") as f:
    f.write("// Generated by mod/make_icons.py. Alpha-only icons, coloured through the style img_recolor.\n#include \"lvgl.h\"\n\n")
    for n, a in ICONS.items():
        f.write(c_array(n, a))

if len(sys.argv) > 1:  # preview of the bottom row of the brew screen, built from the very same pixels
    W, H, Z = 480, 150, 3
    top, bot = (0xE5, 0x85, 0x0F), (0xC3, 0x2D, 0x11)
    cream, red = (0xFF, 0xEE, 0xDE), (0xC3, 0x2D, 0x11)

    def row(n):
        A = 4
        img = Image.new("RGB", (W * A, H * A))
        d = ImageDraw.Draw(img)
        for y in range(H * A):
            t = y / (H * A)
            d.line([(0, y), (W * A, y)], fill=tuple(int(top[i] + (bot[i] - top[i]) * t) for i in range(3)))
        on = n > 1
        for bx, filled in ((116, False), (364, on)):
            box = [(bx - 28) * A, (75 - 28) * A, (bx + 28) * A, (75 + 28) * A]
            if filled:
                d.ellipse(box, fill=cream)
            else:
                d.ellipse(box, outline=cream, width=2 * A)
        d.ellipse([(240 - 60) * A, 15 * A, (240 + 60) * A, 135 * A], fill=cream)
        pts = [(216 + 18, 51 + 13), (216 + 34, 51 + 24), (216 + 18, 51 + 35)]
        d.polygon([(x * A, y * A) for x, y in pts], fill=red)
        for i in range(3):
            a, b = pts[i], pts[(i + 1) % 3]
            d.line([(a[0] * A, a[1] * A), (b[0] * A, b[1] * A)], fill=red, width=14 * A)
            d.ellipse([(a[0] - 7) * A, (a[1] - 7) * A, (a[0] + 7) * A, (a[1] + 7) * A], fill=red)
        img = img.resize((W, H), Image.LANCZOS)

        def paste(mask, x, y, color):
            m = Image.fromarray(mask, "L")
            img.paste(Image.new("RGB", m.size, color), (x, y), m)

        dr, cp = ICONS["jungle_icon_drop"], ICONS["jungle_icon_cup"]
        paste(dr, 116 - dr.shape[1] // 2, 75 - dr.shape[0] // 2 - 1, cream)
        c = red if on else cream
        paste(cp, 364 - 28 + 7, 75 - cp.shape[0] // 2, c)
        d = ImageDraw.Draw(img)
        d.text((364 - 28 + 43, 75 - 2), str(n), fill=c, font=ImageFont.load_default(size=16), anchor="mm")
        return img.resize((W * Z, H * Z), Image.LANCZOS)

    a, b = row(1), row(3)
    out = Image.new("RGB", (a.width, a.height * 2 + 12), (0, 0, 0))
    out.paste(a, (0, 0))
    out.paste(b, (0, a.height + 12))
    out.save(sys.argv[1])
